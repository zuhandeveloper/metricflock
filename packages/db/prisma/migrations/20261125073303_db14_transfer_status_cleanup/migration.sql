-- A-DB-14: drop the dead TransferStatus values INITIATED and TRANSFERRED.
--
-- Evidence: nothing in current code writes either value — transfers are created
-- directly as PENDING_ACCEPTANCE, and the stage7 migration backfilled every
-- TRANSFERRED row to COMPLETED. But INITIATED still lived in
-- OPEN_TRANSFER_STATUSES and in the partial unique index predicate, so a
-- manually-created (or legacy pre-stage7) INITIATED row blocked all new
-- transfers for that website via the index.
--
-- Pre-flight (read-only, run before `prisma migrate deploy`):
--   SELECT status, COUNT(*) FROM "WebsiteTransfer"
--   WHERE status IN ('INITIATED', 'TRANSFERRED') GROUP BY status;
-- TRANSFERRED must be 0 (backfilled by the stage7 migration). INITIATED may be
-- > 0: any such row is a pre-stage7 transfer that was never accepted, and this
-- migration converts it to PENDING_ACCEPTANCE below — no repair needed first.
--
-- Postgres cannot drop an enum value in place, so this is the recreate/rename
-- dance (generated by `prisma migrate diff`). Two hand-added steps surround
-- it: the data conversion runs FIRST (the USING cast below would fail on a
-- legacy INITIATED/TRANSFERRED row), and the partial unique index is dropped
-- before the type change and recreated after (its predicate referenced
-- 'INITIATED', which ceases to exist; Prisma cannot express this index, so
-- it is raw SQL, as in the stage7 migration).

-- 1. Convert any legacy rows to reachable states.
--    INITIATED → PENDING_ACCEPTANCE: a pre-stage7 transfer that was never
--    accepted awaits acceptance, which is exactly PENDING_ACCEPTANCE.
--    TRANSFERRED → COMPLETED: defensive; the stage7 migration already
--    backfilled every TRANSFERRED row, so this should match 0 rows.
UPDATE "WebsiteTransfer" SET "status" = 'PENDING_ACCEPTANCE' WHERE "status" = 'INITIATED';
UPDATE "WebsiteTransfer" SET "status" = 'COMPLETED', "completedAt" = COALESCE("completedAt", "updatedAt") WHERE "status" = 'TRANSFERRED';

-- 2. Drop the partial unique index before the enum loses 'INITIATED'.
DROP INDEX "WebsiteTransfer_one_open_per_website";

-- 3. Enum recreate/rename (prisma migrate diff output, verbatim).
-- AlterEnum
BEGIN;
CREATE TYPE "TransferStatus_new" AS ENUM ('PENDING_ACCEPTANCE', 'PENDING_CONNECTION', 'COMPLETED', 'CANCELLED', 'FAILED', 'EXPIRED');
ALTER TABLE "WebsiteTransfer" ALTER COLUMN "status" DROP DEFAULT;
ALTER TABLE "WebsiteTransfer" ALTER COLUMN "status" TYPE "TransferStatus_new" USING ("status"::text::"TransferStatus_new");
ALTER TYPE "TransferStatus" RENAME TO "TransferStatus_old";
ALTER TYPE "TransferStatus_new" RENAME TO "TransferStatus";
DROP TYPE "TransferStatus_old";
ALTER TABLE "WebsiteTransfer" ALTER COLUMN "status" SET DEFAULT 'PENDING_ACCEPTANCE';
COMMIT;

-- AlterTable
ALTER TABLE "WebsiteTransfer" ALTER COLUMN "status" SET DEFAULT 'PENDING_ACCEPTANCE';

-- 4. Recreate the partial unique index without INITIATED.
CREATE UNIQUE INDEX "WebsiteTransfer_one_open_per_website"
  ON "WebsiteTransfer" ("websiteId")
  WHERE "status" IN ('PENDING_ACCEPTANCE', 'PENDING_CONNECTION');
